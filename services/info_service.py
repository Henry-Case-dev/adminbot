"""Epic 43 — InfoService (R43-2, Section 52.3): info_text.md + кэш в память.

Чтение при старте; запись ТОЛЬКО через save_text() (вызывается хендлером
ПОСЛЕ успешной рендер-валидации превью — D163). Файла нет/пустой → канон
DEFAULT_INFO_TEXT записывается на диск. IO-ошибка чтения → WARNING + кэш =
канон (файл НЕ перезаписываем). Sync-IO оправдан: файл ~1-2 КБ, пути —
только старт и редкие правки админа (не горячий event-loop путь).
"""
import logging

from config.settings import settings

logger = logging.getLogger(__name__)

# КАНОН дефолтной справки (Epic 44 R44-1 → Epic 55 T-431 → Epic 56 T-437 → Epic 57 T-442 → Epic 58 T-447, Section 53.3) — байт-в-байт тест
DEFAULT_INFO_TEXT = """<h1>Гайд по фичам бота с выходом в сеть internet. Никаких слеш-команд, всё работает нативно прямо в диалоге.</h1>

<h2>1. Фактчек сообщений и новостей (чтобы чекать репосты Лехи)</h2>
- Как вызвать: сделай Reply (ответ) на любое сообщение или репост в чате и напиши слово <b><i>фактчек</i></b>.
- С уточнением: если нужно проверить конкретную деталь, допиши вопрос следом.
Например: <b><i>фактчек правда ли склад сгорел?</i></b> или <b><i>фактчек поясни за цифры</i></b>.
Бот поднимет поисковики, проверит достоверность и выдаст вердикт в своем стиле прямо в ответ на исходный пост.

<h2>2. Поиск инфы (кому лень зайти в гугл во время срача)</h2>
- Как вызвать: просто начни сообщение со слов <b><i>найди</i></b>, <b><i>поищи</i></b> или <b><i>загугли</i></b> и дальше пиши суть.
- Примеры: <b><i>загугли почему видеокарта греется в простое</i></b> / <b><i>найди последние новости про новый патч</i></b>
Бот соберет факты из сети и пришлет выжимку реплаем на твое сообщение.
Нюансы: На поиск и <b><i>фактчек</i></b> стоят раздельные кулдауны по 5 минут. Если спамить — бот пошлет вас нахуй.

<h2>3. Пересказ ролика с ютуба (если есть субтитры):</h2>
Способ 1 (реплай): Ответь на сообщение с ютуб-ссылкой и напиши: <b><i>транскрипт</i></b>, <b><i>че за видос</i></b>, <b><i>о чем видео</i></b>, <b><i>поясни за видос</i></b>.
Способ 2 (одной строкой): Просто кинь ссылку и фразу в одном сообщении (<a href="https://youtu.be/">https://youtu.be/</a>... <b><i>поясни за видос</i></b>).
Бот не распознает само видео, он парсит сабы и пересказывает суть.

<h2>4. Пересказ веб-страницы</h2>
Способ 1 (реплай): Ответь на сообщение с ссылкой и напиши: <b><i>поясни за ссылку</i></b>, <b><i>че по ссылке</i></b>, <b><i>о чем статья</i></b>, <b><i>выжимка</i></b>.
Способ 2 (одной строкой): Ссылка + фраза (<a href="https://какой-то-сайт.ru">https://какой-то-сайт.ru</a> <b><i>выжимка</i></b>).
Опять же бот не "видит" веб-страницу, а парсит ее маркдаун версию, пересказывает на свой лад.

<h2>5. Checkup (Здоровье бота)</h2>
Хочешь узнать, жив ли бот и сервак? Команда заставить его посмотреть внутрь себя.
Как вызвать: напиши в чат <b><i>чекап</i></b>, <b><i>ты в порядке</i></b>, <b><i>живой собака</i></b> или <b><i>чекни здоровье</i></b>.
Бот залезет в системные логи, найдет свежие ошибки и токсично пояснит, что отвалилось на сервере.

<h2>6. Прямое обращение к Богу Машине</h2>
 Способ 1 (словами через рот): Бот откликается на <b><i>бот</i></b>, <b><i>ботик</i></b>, <b><i>ботяра</i></b> и <b><i>ботохуета</i></b>. Как вызвать: просто напиши одно из этих слов в чат - бот ответит реплаем на твое сообщение. Робот, работа и ботва не в счет: они его не разбудят.
 Способ 2 (реплай): бот отвечает если ответить (Reply) на его сообщение.
 Способ 3 (тегнуть): Бот ответит на тег через "@"."""


class InfoService:
    def __init__(self, file_path: str = settings.INFO_TEXT_FILE) -> None:
        self._file_path = file_path
        self._cache: str | None = None

    def load(self) -> None:
        """Чтение при старте. FileNotFoundError/пустой файл → записать канон
        (UTF-8) на диск + кэш = канон; OSError чтения → WARNING + кэш = канон
        (файл НЕ перезаписываем — возможно, проблема прав)."""
        try:
            with open(self._file_path, encoding="utf-8") as fh:
                text = fh.read()
        except FileNotFoundError:
            self._write_default()
            self._cache = DEFAULT_INFO_TEXT
            logger.info("[info service] default info_text.md created | file=%s",
                        self._file_path)
        except OSError:
            logger.warning("[info service] read failed → in-memory default | file=%s",
                           self._file_path, exc_info=True)
            self._cache = DEFAULT_INFO_TEXT
        else:
            if text.strip():
                self._cache = text
            else:
                self._write_default()          # пустой файл → канон (не битая справка)
                self._cache = DEFAULT_INFO_TEXT
                logger.warning("[info service] empty file → default written | file=%s",
                               self._file_path)

    def get_text(self) -> str:
        return self._cache if self._cache is not None else DEFAULT_INFO_TEXT

    def save_text(self, text: str) -> None:
        """Перезапись файла + кэш. ВЫЗЫВАТЬ ТОЛЬКО ПОСЛЕ успешного превью (D163).
        OSError — НАВЕРХ (хендлер шлёт пул, кэш остаётся старым)."""
        with open(self._file_path, "w", encoding="utf-8") as fh:
            fh.write(text)
        self._cache = text
        logger.info("[info service] info_text.md updated | file=%s | chars=%d",
                    self._file_path, len(text))

    def _write_default(self) -> None:
        with open(self._file_path, "w", encoding="utf-8") as fh:
            fh.write(DEFAULT_INFO_TEXT)
