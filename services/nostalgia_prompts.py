# CFG-07A-2 (FA-06/G1, 20.10.2026): не-точное эхо служебного токена отказа
# («UNCHANGED, но ...») не ловится точным детектором и раньше ушло бы в чат
# как контент. Публичный текст не должен содержать токен ни в каком
# обрамлении — вызывающие проверяют contains_unchanged_token ДО отправки
# (брак, а не публикация). is_unchanged_response не менялся: контракт
# «ровно UNCHANGED = отказ» цел (spec §3.5.4).
_UNCHANGED_TOKEN_RE = re.compile(r"\bUNCHANGED\b", re.IGNORECASE | re.UNICODE)


def contains_unchanged_token(text: str | None) -> bool:
    """В тексте есть служебный токен UNCHANGED в любом обрамлении
    (регистронезависимо, по границам слова). Никогда не бросает."""
    return bool(_UNCHANGED_TOKEN_RE.search(str(text or "")))


# P0 NOSTALGIA REWORK W1 (27.10.2026, source-2026-10-27 NOST-01): прежний
# узкий страж самоотказа по спискам фраз (_SELF_DECLINE_VERDICT_RES /
# _SELF_DECLINE_NOTHING_RE / _SELF_DECLINE_NOTHING_REV_RE /
# _SELF_DECLINE_ALL_RES / is_self_declining_text) УДАЛЁН — запрещено
# исправлять семантическое поведение перечислением фраз. Отказ теперь
# типизированный вердикт того же LLM-вызова: ровно UNCHANGED (формальный
# контракт сохранён, is_unchanged_response не менялся) или SAY + реплика
# (parse_nostalgia_answer). Проза-самоотказ не является рабочей формой:
# канон требует вердикт, содержательное решение — за моделью/Decision.

_SAY_VERDICT = "SAY"


def parse_nostalgia_answer(raw: str | None) -> tuple[str, str]:
    """Разбор типизированного ответа модели (NOST-01): вердикт первой
    строкой — ровно UNCHANGED или SAY.

    Возвращает (verdict, text):
      * "unchanged" — отказ (формальный контракт UNCHANGED сохранён; текста
        нет, публикация отсутствует);
      * "say"       — content = сама реплика (со второй строки);
      * "legacy"    — ответ без вердикта (старые клиенты/моки): text = сырое
        значение, трактуется как контент (обратная совместимость).
    Детерминированный парсинг служебного маркера, не смысловой анализ
    человеческого текста. Никогда не бросает."""
    value = str(raw or "")
    if is_unchanged_response(value):
        return "unchanged", ""
    first, _sep, rest = value.lstrip().partition("\n")
    if first.strip().upper() == _SAY_VERDICT:
        return "say", rest.strip()
    return "legacy", value


def format_nostalgia_hint(fact_text: str, ts, cap_chars: int) -> str:
    """Маркер слоя A (spec §3.5.1/E1): одна строка
    `nostalgia_hint: вспомни и вплети, если уместно: [ГГГГ-ММ-ДД] текст`.
    Фикс-кап `cap_chars` ДО инжекта (обрезается текст факта, не метка).
    Пустой факт/нулевой кап → ""."""
    text = " ".join(str(fact_text or "").split())
    if not text:
        return ""
    date = _ts_date(ts)
    prefix = f"nostalgia_hint: вспомни и вплети, если уместно: [{date}] "
    cap = max(int(cap_chars or 0), 0)
    if cap <= 0:
        return ""
    budget = max(0, cap - len(prefix))
    if budget <= 0:
        return ""
    return prefix + text[:budget]


def _ts_date(ts) -> str:
    """unix ts → ГГГГ-ММ-ДД (local; битое/пустое → '????-??-??')."""
    try:
        return datetime.datetime.fromtimestamp(int(ts)).strftime("%Y-%m-%d")
    except (TypeError, ValueError, OSError):
        return "????-??-??"


def _speaker_name(row, display_names=None) -> str:
    """Имя автора строки smart_messages (NOST-07.3): актуальный алиас по
    uid (единый каскад summary_aliases: алиас чата → глобальный; резолв
    выполняет вызывающий воркер) → author_name (историческое имя —
    остаётся пригодным, актуальные алиасы им не подменяются) → uid → «?»."""
    uid = _row_get(row, "user_id")
    if display_names and uid not in (None, 0):
        resolved = display_names.get(int(uid))
        if resolved:
            return resolved
    name = str(_row_get(row, "author_name") or "").strip()
    if name:
        return name
    return str(uid) if uid not in (None, 0) else "?"


def _row_get(row, key: str, default=None):
    """Доступ к полю строки (dict ИЛИ sqlite3.Row/aiosqlite.Row)."""
    try:
        return row.get(key, default)
    except AttributeError:
        try:
            return row[key]
        except (KeyError, IndexError, TypeError):
            return default


def _forward_label(row) -> str:
    """Provenance-лейбл forward-строки (ASAP5 W1, 27.10.2026, source §6;
    поля is_forward/forward_source — Epic 28, R28-1): «Переслано: источник»
    — прецедент канонического контекста (canonical_context.
    format_context_item). Не-forward/старые строки без полей → "" (байт-в-
    байт прежний рендер)."""
    try:
        is_fwd = int(_row_get(row, "is_forward") or 0)
    except (TypeError, ValueError):
        is_fwd = 0
    if not is_fwd:
        return ""
    source = _collapse(_row_get(row, "forward_source"))
    return f"Переслано: {source}" if source else "Переслано"


def format_year_back_line(row, display_names=None) -> str:
    """Строка кандидата «N лет назад» (spec §3.5.2): `[Имя ГГГГ-ММ-ДД]: текст`
    — рендер для LLM и лога. ASAP5 W1 (source §6): forward-строки получают
    provenance-лейбл «Переслано: источник» внутри головы — репост внешней
    новости больше не выглядит как реплика участника чата. P0 REWORK W1
    (NOST-07.3): `display_names` — резолв актуального имени по Telegram
    user_id (алиас чата → глобальный); исторический author_name используется
    только без алиаса. Текст исторических сообщений не переписывается."""
    text = " ".join(str(_row_get(row, "text") or "").split())
    if not text:
        return ""
    head = (f"{_speaker_name(row, display_names)} "
            f"{_ts_date(_row_get(row, 'timestamp'))}")
    provenance = _forward_label(row)
    if provenance:
        head += f" | {provenance}"
    return f"[{head}]: {text}"


def _years_ago_label(years: int) -> str:
    """«N год/года/лет назад» для заголовка эпизода (русские формы)."""
    years = max(0, int(years or 0))
    if years == 0:
        return "этим годом"
    if years % 10 == 1 and years % 100 != 11:
        return f"{years} год назад"
    if years % 10 in (2, 3, 4) and years % 100 not in (12, 13, 14):
        return f"{years} года назад"
    return f"{years} лет назад"


def render_episode_block(ep: dict) -> str:
    """Блок одного исторического эпизода для user-блока LLM (P0 REWORK W1,
    NOST-04): честный заголовок «N лет назад (ГГГГ-ММ-ДД — ГГГГ-ММ-ДД)» по
    фактическим границам сегмента + строки первичных сообщений (рендер
    format_year_back_line — provenance сохраняется). Дата-диапазон не
    утверждает час события (NOST-02.2). Пустой эпизод → ""."""
    lines = [str(l) for l in (ep.get("lines") or []) if l]
    if not lines:
        return ""
    head = (f"{_years_ago_label(ep.get('years_ago'))} "
            f"({_ts_date(ep.get('start_ts'))} — {_ts_date(ep.get('end_ts'))}):")
    return head + "\n" + "\n".join(lines)


def format_golden_line(row: dict) -> str:
    """Строка «золотого» факта (spec §3.5.2): `[ГГГГ-ММ-ДД] текст факта`.
    FIX-CORRECTIVE-R1 (nostalgia-audit §3, 21.10.2026): непустой
    `target_user` рендерится именем-лейблом «[Имя]» (прецедент
    _render_meme/R16: имя-лейбл, не id) — модель не привязывает факт
    не к тому человеку. Пустой/отсутствующий target_user → формат прежний."""
    text = " ".join(str(_row_get(row, "fact") or "").split())
    if not text:
        return ""
    ts = _row_get(row, "rag_ts") or _row_get(row, "created_at")
    target = _collapse(_row_get(row, "target_user"))
    if target:
        return f"[{_ts_date(ts)}] [{target}] {text}"
    return f"[{_ts_date(ts)}] {text}"


def _collapse(text) -> str:
    """Санитизация строки: схлопывание любых пробелов/переводов строк."""
    return " ".join(str(text or "").split())


def _cap_words(text: str, cap: int) -> str:
    """Обрезка до `cap` символов по границе слова (кап лора)."""
    if cap <= 0:
        return ""
    if len(text) <= cap:
        return text
    cut = text[:cap]
    head = cut.rsplit(" ", 1)[0].rstrip()
    return head or cut.rstrip()


def _cap_chars(text: str, cap: int) -> str:
    """Жёсткая обрезка до `cap` символов (кап текста одного мема)."""
    if cap <= 0:
        return ""
    return text[:cap].rstrip() if len(text) > cap else text


def _render_meme(row) -> str:
    """Строка мема: `- {fact}`; при непустом `target_user` → `- [label] {fact}`
    (R16: target_user — имя-лейбл, не id). Пустой факт → ""."""
    fact = _cap_chars(_collapse(_row_get(row, "fact")), _MEME_MAX_CHARS)
    if not fact:
        return ""
    target = _collapse(_row_get(row, "target_user"))
    return f"- [{target}] {fact}" if target else f"- {fact}"


def build_nostalgia_user(year_lines: list[str], golden_lines: list[str],
                         lore: str = "", memes=None,
                         active: bool = False,
                         episodes: list[dict] | None = None) -> str:
    """User-блок LLM-вызова (spec §3.5.4 + round 10.15 §4): «Вот память:» +
    кандидаты + аддитивные секции «Лор чата»/«Локальные мемы» (пустые секции
    опускаются; всё пусто → "").

    P0 REWORK W1 (NOST-02/04): при непустом `episodes` историческая секция —
    блоки эпизодов разных лет (render_episode_block); голый `year_lines`
    путь сохранён байт-в-байт для обратной совместимости (легаси-вызовы и
    прежние тесты). Сигнатура обратно совместима:
    `build_nostalgia_user(year, golden)` работает как раньше. `active=True`
    — сценарий A: преамбула не утверждает «в чате давно тихо»."""
    parts: list[str] = []
    episode_blocks = [b for b in (render_episode_block(e)
                                  for e in (episodes or [])) if b]
    if episode_blocks:
        parts.append("Эпизоды из истории чата за прошлые годы:\n\n"
                     + "\n\n".join(episode_blocks))
    elif year_lines:
        parts.append("События примерно год назад в этот день:\n"
                     + "\n".join(str(l) for l in year_lines))
    if golden_lines:
        parts.append("Старые факты по последней теме разговора:\n"
                     + "\n".join(f"- {l}" for l in golden_lines))
    lore_text = _cap_words(_collapse(lore), _LORE_MAX_CHARS)
    if lore_text:
        parts.append("Лор чата (как тут принято общаться):\n" + lore_text)
    meme_lines = [l for l in (_render_meme(r)
                              for r in (memes or [])[:_MEMES_LIMIT]) if l]
    if meme_lines:
        parts.append("Локальные мемы (местные ярлыки и шутки):\n"
                     + "\n".join(meme_lines))
    if not parts:
        return ""
    head = ("В чате сейчас живая беседа. Вот память:" if active
            else "В чате давно тихо. Вот память:")
    return head + "\n" + "\n\n".join(parts)


def clean_llm_text(raw: str | None, cap_chars: int = 400) -> str:
    """Нормализация текста ответа LLM (spec §3.5.4): strip, схлопывание
    пробелов/пустых строк, кап `cap_chars` символов. UNCHANGED/пусто →
    "" (вызывающий решает статус по is_unchanged_response ДО обрезки)."""
    text = re.sub(r"\s+", " ", str(raw or "")).strip()
    if not text:
        return ""
    cap = max(int(cap_chars or 0), 0)
    if cap > 0 and len(text) > cap:
        return text[:cap].rstrip()
    return text
