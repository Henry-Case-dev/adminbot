# -*- coding: utf-8 -*-
"""Synthetic smoke tests for the TIME-03 real-archive S1-S7 harness.

Local validation only: no production, no SSH, no real archive. The fixture is
generated by the vendored MEM-07 `make_fixture.py` and opened read-only by the
harness.
"""
from __future__ import annotations

import json
import os
import subprocess
import sys
from pathlib import Path

import pytest

HERE = Path(__file__).resolve().parent
ROOT = Path(__file__).resolve().parents[6]
HARNESS = HERE / "time03_scenarios.py"
CHAT = -1002661910336


def _run(args, tmp_path, env_extra=None):
    env = dict(os.environ)
    env["PYTHONPATH"] = str(ROOT) + os.pathsep + env.get("PYTHONPATH", "")
    if env_extra:
        env.update(env_extra)
    head = subprocess.run(
        ["git", "-C", str(ROOT), "rev-parse", "HEAD"],
        capture_output=True, text=True, encoding="utf-8",
        errors="replace").stdout.strip()
    return subprocess.run(
        [sys.executable, str(HARNESS), *args, "--code-root", str(ROOT),
         "--expected-sha", head],
        cwd=str(ROOT), env=env, capture_output=True, text=True,
        encoding="utf-8", errors="replace", timeout=1200)


def _load(path):
    return json.loads(Path(path).read_text(encoding="utf-8"))


def test_dry_run(tmp_path):
    proc = _run(["--dry-run", "--variant", "candidate",
                 "--chat-id", str(CHAT), "--out", str(tmp_path / "dry")],
                tmp_path)
    assert proc.returncode == 0, proc.stderr[-2000:]
    payload = json.loads(proc.stdout)
    assert payload["schema"] == "vmq-time03-scenarios/1"
    assert payload["expected_code_root_sha"].startswith("65edc92dc")


def test_fixture_run_structural(tmp_path):
    out = tmp_path / "fixture"
    proc = _run(["--fixture", "--variant", "candidate",
                 "--chat-id", str(CHAT), "--out", str(out)], tmp_path)
    assert proc.returncode in (0, 1), proc.stderr[-4000:]
    payload = _load(out / "time03-scenarios-candidate.json")
    assert payload["schema"] == "vmq-time03-scenarios/1"
    assert payload["mode"] == "fixture"
    assert payload["variant"] == "candidate"
    assert payload["scenario_count"] == 7
    assert payload["snapshot"]["quick_check"] == "ok"
    assert payload["snapshot"]["user_version"] == 48
    assert payload["snapshot_sha256_after"] == payload["snapshot"]["sha256"]
    assertions = {a["id"]: a["status"] for a in payload["assertions"]}
    for aid in ("SNAPSHOT-READONLY", "CONFIG-FAIL-CLOSED", "NETWORK-OFF",
                "SCENARIOS-EXECUTED", "NO-FABRICATED-REFS",
                "NO-TEXT-NAMES"):
        assert assertions[aid] == "pass", (aid, assertions)
    rows = {row["id"]: row for row in payload["scenarios"]}
    assert set(rows) == {"S1", "S2", "S3", "S4", "S5", "S6", "S7"}
    assert rows["S7"]["status"] == "informational"
    assert any(row["status"] in ("pass", "informational")
               for row in rows.values())
    for row in rows.values():
        m = row.get("metrics") or {}
        if not m:
            continue
        for key in ("required_fact_recall", "relevance",
                    "episode_completeness", "temporal_correctness",
                    "participant_attribution", "source_proof",
                    "latency_cost"):
            assert key in m, (row["id"], key)
        for key in ("required_fact_recall", "relevance",
                    "episode_completeness", "temporal_correctness",
                    "participant_attribution", "source_proof"):
            part = m[key]
            assert "den" in part and "value" in part, (row["id"], key, part)
        assert "latency_cost" in m
    text = json.dumps(payload, ensure_ascii=False)
    for marker in ("SECRET_FACT_TEXT_MEM07", "SECRET_MSG_TEXT_MEM07",
                   "Участник Один", "Участник Два", "Участник Три"):
        assert marker not in text, marker
    # No year-share success metric in the acceptance output.
    assert "year_share" not in text and "share_2026" not in text


def test_handwritten_config_rejected(tmp_path):
    out = tmp_path / "gate"
    cfg = tmp_path / "effective.json"
    cfg.write_text(json.dumps({"graph_rag_enabled": True,
                               "graph_rag_facts_limit": 10}),
                   encoding="utf-8")
    proc = _run(["--fixture", "--variant", "candidate",
                 "--chat-id", str(CHAT), "--effective-config", str(cfg),
                 "--out", str(out)], tmp_path)
    assert proc.returncode == 2, proc.stderr[-2000:]
    payload = _load(out / "time03-scenarios-candidate.json")
    assert payload["status"] == "not_executed"
    reason = str(payload.get("technical_reason") or "")
    assert "effective_config" in reason or reason.startswith("missing:")


def test_fixture_text_not_stored_in_entries(tmp_path):
    out = tmp_path / "fixture2"
    proc = _run(["--fixture", "--variant", "candidate",
                 "--chat-id", str(CHAT), "--out", str(out)], tmp_path)
    assert proc.returncode in (0, 1), proc.stderr[-4000:]
    payload = _load(out / "time03-scenarios-candidate.json")
    for row in payload["scenarios"]:
        entry = row.get("entry") or {}
        assert "text" not in entry
        assert "fact" not in entry
        assert "query" not in entry
        assert "query_template" not in entry
        assert "payload_sha256" in (entry.get("writer") or {})
