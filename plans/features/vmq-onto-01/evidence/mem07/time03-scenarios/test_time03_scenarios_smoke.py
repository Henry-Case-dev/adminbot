def _run(args, tmp_path, env_extra=None):
    env = dict(os.environ)
    env.pop("PYTHONPATH", None)
    if env_extra:
        env.update(env_extra)
    head = subprocess.run(
        ["git", "-C", str(ROOT), "rev-parse", "HEAD"],
        capture_output=True, text=True, encoding="utf-8",
        errors="replace").stdout.strip()
    return subprocess.run(
        [sys.executable, str(HARNESS), *args, "--code-root", str(ROOT),
         "--expected-sha", head],
        cwd=str(ROOT), env=env, capture_output=True, text=True,
        encoding="utf-8", errors="replace", timeout=1200)


def _load(path):
    return json.loads(Path(path).read_text(encoding="utf-8"))


def test_dry_run(tmp_path):
    proc = _run(["--dry-run", "--variant", "candidate",
                 "--chat-id", str(CHAT), "--out", str(tmp_path / "dry")],
                tmp_path)
    assert proc.returncode == 0, proc.stderr[-2000:]
    payload = json.loads(proc.stdout)
    assert payload["schema"] == "vmq-time03-scenarios/2"
    assert payload["expected_code_root_sha"].startswith("65edc92dc")


